# Regenerates the 16 px Noto Sans JP Medium fallback for Japanese captions.
# Needs curl, Python 3 with fontTools, and npx.
set -eu

HERE="$(cd "$(dirname "$0")/../.." && pwd)"
OUT="$HERE/components/muse/fonts/muse_font_jp_noto_16.c"
TMP="$(mktemp -d "$HERE/.jp-font.XXXXXX")"
trap 'rm -rf "$TMP"' EXIT
export npm_config_cache="$TMP/npm"

FONT_PATH="notofonts/noto-cjk/main/Sans/SubsetOTF/JP/NotoSansJP-Medium.otf"
curl -fsSL -o "$TMP/noto.otf" \
    "https://github.com/notofonts/noto-cjk/raw/main/Sans/SubsetOTF/JP/NotoSansJP-Medium.otf" ||
    curl -fsSL -o "$TMP/noto.otf" "https://raw.githubusercontent.com/$FONT_PATH"

CODEPOINTS=$(python3 - "$TMP/noto.otf" <<'PY'
import sys
from fontTools.ttLib import TTFont

jis = set()
for ku in (*range(1, 9), *range(16, 85)):
    for ten in range(1, 95):
        try:
            jis.add(ord(bytes([0xA0 + ku, 0xA0 + ten]).decode("euc_jp")))
        except UnicodeDecodeError:
            pass

symbols = {
    0x00A5, 0x00B0, 0x00B1, 0x00D7, 0x00F7, 0x2010, 0x2013, 0x2014,
    0x2015, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2025, 0x2026,
    0x203B, 0x2190, 0x2191, 0x2192, 0x2193, 0x21D2, 0x21D4, 0x2212,
    0x25A0, 0x25A1, 0x25B2, 0x25B3, 0x25BC, 0x25BD, 0x25C6, 0x25C7,
    0x25CB, 0x25CE, 0x25CF, 0x2605, 0x2606, 0x266A, 0x301C, 0xFF5E,
}
with TTFont(sys.argv[1]) as font:
    cmap = font.getBestCmap()
    codepoints = (jis | symbols | set(range(0x3000, 0x3100)) |
                  set(range(0xFF00, 0xFFF0))) & cmap.keys()
print(",".join(hex(cp) for cp in sorted(codepoints)))
PY
)

npx -y lv_font_conv@1.5.3 --font "$TMP/noto.otf" --size 16 --bpp 4 \
    --format lvgl --lv-font-name muse_font_jp_noto_16 --no-compress \
    -r "$CODEPOINTS" -o "$TMP/font.c"
sed -e 's|#include "lvgl/lvgl.h"|#include "lvgl.h"|' \
    -e 's/^ \* Opts:.*/ * Noto Sans JP Medium. See LICENSE-noto-b-ja.txt for copyright and license.\n * Generated by tools\/muse\/gen_jp_noto_font.sh./' \
    -e 's/[[:blank:]]*$//' -e '${/^$/d;}' "$TMP/font.c" > "$OUT"
echo "wrote $OUT"
